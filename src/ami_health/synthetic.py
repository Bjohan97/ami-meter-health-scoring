"""SYNTHETIC fleet with known archetypes, for examples and tests.

Nothing here comes from a real utility or meter. Each meter is generated with one archetype and
the expected diagnosis is written to ``archetypes.csv``.
"""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

ARCHETYPES = {
    # archetype: expected diagnosis
    "healthy": "OK",
    "hardware": "HARDWARE_SUSPECT",
    "intermittent": "INTERMITTENT_COMMUNICATION",
    "day_loss": "DAY_LEVEL_LOSS",
    "no_data": "NO_DATA",
    "tamper": "TAMPER_OPEN",
    "tamper_closed": "OK",
    "power_outage": "POWER_OUTAGE",
    "voltage": "VOLTAGE_QUALITY",
    "deteriorating": "DETERIORATING",
    "group_outage": "GROUP_ISSUE",
}


def _write(df: pd.DataFrame, path: Path) -> None:
    df.to_csv(path, index=False, lineterminator="\n")


def generate(out_dir: str | Path, days: int = 14, start: str = "2026-01-04", seed: int = 7) -> dict:
    if days < 12:
        raise ValueError("the synthetic archetypes need at least 12 days")
    rng = np.random.default_rng(seed)
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    dates = pd.date_range(start, periods=days, freq="D")
    plan = []                                      # (meter, dcu, archetype)
    n = 0
    for dcu, arche in (("DCU-A", ["healthy"] * 6 + ["hardware", "intermittent", "day_loss", "no_data"]),
                       ("DCU-B", ["healthy"] * 5 + ["tamper", "tamper_closed", "power_outage", "voltage", "deteriorating"]),
                       ("DCU-C", ["group_outage"] * 6)):
        for a in arche:
            n += 1
            plan.append((f"MTR-{n:04d}", dcu, a))

    md_rows, slot_rows, volt_rows, ev_rows = [], [], [], []
    for meter, dcu, a in plan:
        for di, d in enumerate(dates):
            slots = set(range(96))
            if a == "hardware":                                    # always 02:00-04:00 missing
                slots -= set(range(8, 16))
            elif a == "intermittent":                              # ~10 % random slots missing
                slots -= set(rng.choice(96, size=10, replace=False).tolist())
            elif a == "day_loss" and di in (3, 7, 10):
                slots = set()
            elif a == "no_data":
                slots = set()
            elif a == "power_outage" and di in (5, 6):
                slots -= set(range(40, 96))
            elif a == "deteriorating":
                k = int(round(96 * 0.6 * di / (days - 1)))
                slots -= set(range(96 - k, 96))
            elif a == "group_outage" and 4 <= di <= 9:
                slots = set()
            md_rows.append((meter, d.strftime("%Y-%m-%d"), 96, len(slots)))
            slot_rows += [(meter, d.strftime("%Y-%m-%d"), s) for s in sorted(slots)]
            for h in range(24):
                v = 246.0 if a == "voltage" else 225.0
                volt_rows.append((meter, (d + pd.Timedelta(hours=h)).strftime("%Y-%m-%d %H:%M"),
                                  round(float(v + rng.normal(0, 2)), 1), "VALID"))
        if a in ("tamper", "tamper_closed"):
            ev_rows.append((meter, dates[2].strftime("%Y-%m-%d 10:00"), "Terminal cover opened"))
            if a == "tamper_closed":
                ev_rows.append((meter, dates[2].strftime("%Y-%m-%d 10:20"), "Terminal cover closed"))
        if a == "power_outage":
            for di in (5, 6):
                ev_rows.append((meter, dates[di].strftime("%Y-%m-%d 10:00"), "Long power failure"))

    _write(pd.DataFrame(md_rows, columns=["meter_id", "local_date", "expected_slots", "received"]), out / "meter_days.csv")
    _write(pd.DataFrame(slot_rows, columns=["meter_id", "local_date", "slot_index"]), out / "slots.csv")
    _write(pd.DataFrame(volt_rows, columns=["meter_id", "ts_local", "voltage", "quality"]), out / "voltage.csv")
    _write(pd.DataFrame(ev_rows, columns=["meter_id", "ts_local", "description"]), out / "events.csv")
    _write(pd.DataFrame([(m, g) for m, g, _ in plan], columns=["meter_id", "dcu_id"]), out / "groups.csv")
    _write(pd.DataFrame([(m, a, ARCHETYPES[a]) for m, _, a in plan],
                        columns=["meter_id", "archetype", "expected_diagnosis"]), out / "archetypes.csv")
    (out / "README.md").write_text(
        "# Synthetic fleet\n\nEvery file here is **synthetic**, generated by `ami_health.synthetic` (seed "
        f"{seed}); it is not real meter data.\n`archetypes.csv` lists the archetype of each meter and the "
        "diagnosis the tool must produce.\n", encoding="utf-8", newline="\n")
    return {"meters": len(plan), "days": days, "slots": len(slot_rows)}
